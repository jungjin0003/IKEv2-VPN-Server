export function t(key, vars) {
    var s = (I18N[LANG] && I18N[LANG][key]);
    if (s == null) s = I18N.en[key];
    if (s == null) s = key;
    if (vars) { for (var k in vars) s = s.split("{" + k + "}").join(vars[k]); }
    return s;
}
